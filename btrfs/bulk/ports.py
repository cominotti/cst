"""btrfs-bulk's ports: the changes made in the home as its user, the
read-only looks at the home (as root: lstat, no link followed), the
program's own state files, the rest of the machine (open files,
btrfs-snapshot, Steam's processes, the clock, alerts) and its output.
"""

from __future__ import annotations

from collections.abc import Collection
from collections.abc import Sequence
from typing import Protocol

from btrfs.bulk.domain import (
    Ctx,
    FileRead,
    Item,
    ItemJournal,
    SteamJournal,
    SteamPart,
    TreeSize,
)


class UserFilesPort(Protocol):
    """Each call runs in a child process with the user's uid, gids and HOME
    (as root; a run that is the user already runs it here). An exception
    there is raised here again (Unexpected as itself, others as RuntimeError)."""

    def mkdirs(self, bulk: str, rel: str, *, nocow: bool) -> str:
        """Create bulk/rel folder by folder; nocow: +C from bulk/NOCOW_TOP down."""
        ...

    def rmtree(self, path: str) -> None: ...

    def rmdir(self, path: str) -> None: ...

    def create_bulk(self, bulk: str) -> bool: ...

    def relabel(self, path: str) -> bool: ...

    def write_tag(self, bulk: str) -> bool: ...

    def symlink(self, link: str, target: str) -> bool: ...

    def prepare(self, src: str, new: str, *, nocow: bool) -> int:
        """Copy src into new and check it; the ctime stamp (ns) taken before the copy."""
        ...

    def clock(self, near: str) -> int: ...

    def commit(self, j: ItemJournal) -> bool: ...

    def late_write(self, j: ItemJournal) -> bool: ...

    def new_written(self, j: ItemJournal) -> bool: ...

    def rollback(self, j: ItemJournal) -> bool: ...

    def finish(self, j: ItemJournal) -> bool: ...

    def move_subvol(self, link: str, target: str) -> bool: ...

    def set_nocow_dirs(self, top: str) -> bool: ...

    def flatpak(self, app: str, path: str) -> str:
        """absent | ok | added: the app may use path (an override added when missing)."""
        ...

    def flatpak_state(self, app: str, path: str) -> str:
        """absent | ok | missing."""
        ...

    def read(self, path: str) -> FileRead | None:
        """A regular file (None: absent); a symlink or anything else: Unexpected."""
        ...

    def reflink_probe(self, src_file: str, library: str) -> bool: ...

    def steam_prepare(self, parts: Sequence[SteamPart]) -> int:
        """Copy and check every part (a real copy runs at idle priority in a
        child of its own); the ctime stamp (ns) taken before the copy."""
        ...

    def steam_drop_news(self, j: SteamJournal) -> bool: ...

    def steam_changed(self, j: SteamJournal) -> bool: ...

    def steam_switch(self, j: SteamJournal) -> bool: ...

    def steam_late(self, j: SteamJournal) -> bool: ...

    def steam_new_written(self, j: SteamJournal) -> bool: ...

    def steam_rollback(self, j: SteamJournal) -> bool: ...

    def steam_finish(self, j: SteamJournal) -> bool: ...

    def write_marker(self, path: str, contentid: str) -> bool: ...

    def write_vdf_pair(
        self,
        files: Sequence[str],
        expect: Sequence[bytes],
        expect_mtime: Sequence[int],
        data: bytes,
        ts: str,
        *,
        backup: bool,
    ) -> list[int]:
        """data over both libraryfolders.vdf, each still as read; the new mtimes."""
        ...


class HomeTreePort(Protocol):
    """Looks at the home that never follow a link (safe as root)."""

    def kind(self, path: str) -> str:
        """absent | link | dir | other (lstat)."""
        ...

    def chain(self, base: str, rel: str) -> str:
        """ok | absent | 'symlink:<path>' | 'file:<path>' for every component of base/rel."""
        ...

    def empty_dir(self, path: str) -> bool: ...

    def entries_nofollow(self, path: str) -> list[str]: ...

    def link_target(self, path: str) -> str: ...

    def readlink(self, path: str) -> str: ...

    def realpath(self, path: str) -> str: ...

    def is_subvol(self, path: str) -> bool: ...

    def is_nocow(self, path: str) -> bool: ...

    def has_mount(self, path: str) -> bool: ...

    def cow_data(self, top: str) -> tuple[int, bool]: ...

    def tree_stats(self, top: str, uid: int | None = None) -> tuple[int, int, bool, int]: ...

    def du_bytes(self, path: str) -> TreeSize: ...

    def free_bytes(self, path: str) -> int: ...

    def owner(self, path: str) -> int: ...

    def size(self, path: str) -> int: ...

    def is_regular(self, path: str) -> bool: ...

    def my_uid(self) -> int:
        """The uid this program runs as."""
        ...

    def target_state(self, ctx: Ctx, item: Item) -> str: ...

    def bulk_state(self, ctx: Ctx) -> str: ...

    def tag_state(self, ctx: Ctx) -> str: ...

    def nocow_parents(self, ctx: Ctx, item: Item) -> list[str]: ...

    def steam_manifests(self, folder: str) -> set[str]: ...

    def newest_backup(self, path: str) -> str | None: ...

    def steam_nocow_scan(self, top: str) -> tuple[int, str, str]: ...


class BulkStatePort(Protocol):
    """btrfs-bulk's own files: the journals, the boot flag, the keep list,
    convert-plan and the run lock."""

    def jpath(self, ident: str) -> str: ...

    def jexists(self, ident: str) -> bool: ...

    def jwrite(self, ident: str, j: ItemJournal | SteamJournal) -> None: ...

    def jread_item(self, ident: str) -> ItemJournal | None: ...

    def jread_steam(self, ident: str) -> SteamJournal | None: ...

    def newer_journal(self, ident: str) -> str | None: ...

    def jdrop(self, ident: str) -> None: ...

    def journals(self) -> list[str]: ...

    def steam_journal_ids(self) -> list[str]: ...

    def read_flag(self) -> list[str]: ...

    def flag_add(self, ident: str) -> None: ...

    def write_flag(self, ids: Sequence[str]) -> None: ...

    def flag_exists(self) -> bool: ...

    def read_keep(self) -> tuple[set[str], list[str]]: ...

    def edit_keep(self, add: Sequence[str], remove: Collection[str]) -> None: ...

    def prune_convert_plan(self, drop: Collection[str]) -> bool:
        """Drop the plan's lines for these paths; True if the file changed."""
        ...

    def run_lock(self) -> int:
        """Wait for the run lock (shared with btrfs-snapshot); a handle for release()."""
        ...

    def release(self, lock: int) -> None: ...


class BootCounterPort(Protocol):
    """The boots that tried the moves (cst_core's CounterFile)."""

    def count(self) -> int:
        """0: none, or a counter that cannot be read."""
        ...

    def save(self, count: int) -> None:
        """Durably, before the moves start."""
        ...

    def remove(self) -> None: ...

    def forget(self) -> None:
        """Remove the counter if there is one."""
        ...


class HostPort(Protocol):
    """The rest of the machine."""

    def busy_paths(self, paths: Sequence[str], home: str) -> set[str]: ...

    def convert_bulk_dir(self, bulk: str) -> list[str]:
        """btrfs-snapshot convert-one: what it printed."""
        ...

    def steam_running(self, ctx: Ctx) -> list[str]: ...

    def snapshot_guard(self) -> dict[str, int]: ...

    def alert(self, title: str, body: str) -> None: ...

    def now(self) -> float:
        """A monotonic clock (seconds)."""
        ...

    def new_contentid(self) -> str: ...


class OutputPort(Protocol):
    """What btrfs-bulk prints: log lines (flushed) and plan/status lines."""

    def log(self, msg: str) -> None: ...

    def say(self, line: str) -> None: ...
